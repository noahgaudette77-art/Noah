// Writes src/room/zones.gen.ts from the asset manifest: each zone's files and its 32 px placeholder.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, manifest } from './lib.mjs';
const m = manifest().generated;
const ids = ['sky-entrance', 'sky-bench', 'sky-mesh', 'sky-lane', 'sky-ceiling'];
const rows = ids.map((id) => `  '${id.slice(4)}': { phone: 'assets/room/${id}-2k.webp', desktop: 'assets/room/${id}-4k.webp', placeholder: '${m[id]?.placeholder ?? ''}' },`);
writeFileSync(join(ROOT, 'src/room/zones.gen.ts'), `// Generated by tools/gen-room-index.mjs from public/assets/manifest.json. Do not edit.\nexport const ZONE_FILES = {\n${rows.join('\n')}\n} as const;\nexport type ZoneId = keyof typeof ZONE_FILES;\n`);
console.log('src/room/zones.gen.ts written');

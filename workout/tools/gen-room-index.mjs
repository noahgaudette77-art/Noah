// Writes src/room/zones.gen.ts: each zone's backdrop photo (1980s gym, no people) and a tiny placeholder.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import sharp from 'sharp';
import { ASSETS, ROOT } from './lib.mjs';
const MAP = { entrance: 'bg80-entrance', bench: 'bg80-bench', mesh: 'bg80-wall', lane: 'bg80-floor', ceiling: 'bg80-ceiling' };
const rows = [];
for (const [zone, id] of Object.entries(MAP)) {
  const tiny = await sharp(join(ASSETS, 'art', `${id}.webp`)).resize(18, 32).blur(0.6).webp({ quality: 50 }).toBuffer();
  rows.push(`  '${zone}': { photo: 'assets/art/${id}.webp', avif: 'assets/art/${id}.avif', placeholder: 'data:image/webp;base64,${tiny.toString('base64')}' },`);
}
writeFileSync(join(ROOT, 'src/room/zones.gen.ts'), `// Generated by tools/gen-room-index.mjs. Do not edit.\nexport const ZONE_FILES = {\n${rows.join('\n')}\n} as const;\nexport type ZoneId = keyof typeof ZONE_FILES;\n`);
console.log('src/room/zones.gen.ts written');
